def ministry_of(text: str) -> str:
    """텍스트에서 가장 먼저 등장하는 기관명. 없으면 '정부'."""
    t = text or ""
    best, best_pos = None, len(t) + 1
    for name in MINISTRIES:
        pos = t.find(name)
        if pos != -1 and pos < best_pos:
            best, best_pos = name, pos
    return best or "정부"
